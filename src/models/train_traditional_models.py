# ============================================================
# Quick-mode sampling
# ============================================================

def create_quick_training_mask(
    train_indices,
    max_samples=200000,
):
    """
    Use a reproducible subset for code debugging.

    This is NOT used in the final experiment unless --quick
    is explicitly supplied.
    """

    if len(
        train_indices
    ) <= max_samples:

        return train_indices

    rng = np.random.default_rng(
        RANDOM_STATE
    )

    selected = rng.choice(
        train_indices,
        size=max_samples,
        replace=False,
    )

    selected.sort()

    return selected


# ============================================================
# Main experiment
# ============================================================

def run_experiment(
    df,
    feature_columns,
    current_raw_columns,
    quick=False,
    max_train=200000,
    max_test=0,
    model_output_dir=None,
):
    """
    Train and evaluate all models for all four KPI targets.
    """

    print(
        "\nPreparing feature matrices..."
    )

    # --------------------------------------------------------
    # Train/test masks
    # --------------------------------------------------------

    is_train = (
        df[
            "is_train"
        ]
        .to_numpy(
            dtype=bool
        )
    )

    train_indices = np.flatnonzero(
        is_train
    )

    test_indices = np.flatnonzero(
        ~is_train
    )

    if quick:

        train_indices = (
            create_quick_training_mask(
                train_indices,
                max_samples=max_train,
            )
        )

        if max_test and max_test < len(test_indices):
            rng = np.random.default_rng(RANDOM_STATE)
            test_indices = np.sort(
                rng.choice(test_indices, size=max_test, replace=False)
            )

        print(
            "\nQUICK MODE enabled."
        )

        print(
            "This mode is only for debugging "
            "and must not be used for the final report."
        )

    # --------------------------------------------------------
    # Shared feature matrix
    # --------------------------------------------------------

    all_features = (
        df[
            feature_columns
        ]
        .to_numpy(
            dtype=np.float32
        )
    )

    X_train = all_features[
        train_indices
    ]

    X_test = all_features[
        test_indices
    ]

    del all_features

    target_times_test = (
        df[
            "target_time"
        ]
        .to_numpy(
            dtype=np.int16
        )[
            test_indices
        ]
    )

    print(
        f"\nTraining matrix: "
        f"{X_train.shape}"
    )

    print(
        f"Testing matrix:  "
        f"{X_test.shape}"
    )

    # --------------------------------------------------------
    # Results containers
    # --------------------------------------------------------

    metrics_records = []
    prediction_records = []

    # --------------------------------------------------------
    # Four target KPIs
    # --------------------------------------------------------

    for target_index, kpi in enumerate(
        KPI_COLUMNS
    ):

        print(
            "\n"
            + "=" * 70
        )

        print(
            f"Target KPI: {kpi}(t+1)"
        )

        print(
            "=" * 70
        )

        target_column = (
            f"target_{kpi}"
        )

        raw_current_column = (
            current_raw_columns[
                target_index
            ]
        )

        # ----------------------------------------------------
        # Ground truth
        # ----------------------------------------------------

        all_target = (
            df[
                target_column
            ]
            .to_numpy(
                dtype=np.float32
            )
        )

        y_train = (
            all_target[
                train_indices
            ]
        )

        y_test = (
            all_target[
                test_indices
            ]
        )

        del all_target

        # ----------------------------------------------------
        # Actual mean by target time
        # ----------------------------------------------------

        (
            unique_test_times,
            actual_mean,
        ) = aggregate_by_time(
            target_times_test,
            y_test,
        )

        # ----------------------------------------------------
        # Persistence baseline
        #
        # y_hat(t+1) = y(t)
        # ----------------------------------------------------

        persistence_pred = (
            df[
                raw_current_column
            ]
            .to_numpy(
                dtype=np.float32
            )[
                test_indices
            ]
        )

        (
            mae,
            rmse,
            r2,
        ) = calculate_metrics(
            y_test,
            persistence_pred,
        )

        metrics_records.append({
            "target": kpi,
            "model": "Persistence",
            "MAE": mae,
            "RMSE": rmse,
            "R2": r2,
            "fit_seconds": 0.0,
            "predict_seconds": 0.0,
            "train_rows": len(
                train_indices
            ),
            "test_rows": len(
                test_indices
            ),
            "feature_count": len(
                feature_columns
            ),
        })

        print(
            "\nPersistence"
        )

        print(
            f"  MAE:  {mae:.6f}"
        )

        print(
            f"  RMSE: {rmse:.6f}"
        )

        print(
            f"  R²:   {r2:.6f}"
        )

        (
            _,
            persistence_mean,
        ) = aggregate_by_time(
            target_times_test,
            persistence_pred,
        )

        for (
            target_time,
            actual_value,
            prediction_value,
        ) in zip(
            unique_test_times,
            actual_mean,
            persistence_mean,
        ):

            prediction_records.append({
                "target": kpi,
                "model": (
                    "Persistence"
                ),
                "target_time": int(
                    target_time
                ),
                "actual_mean": float(
                    actual_value
                ),
                "prediction_mean": float(
                    prediction_value
                ),
            })

        del persistence_pred

        # ----------------------------------------------------
        # Required ML models
        # ----------------------------------------------------

        models = build_models(
            quick=quick
        )

        for (
            model_name,
            model,
        ) in models.items():

            print(
                f"\nTraining "
                f"{model_name}..."
            )

            # ------------------------------------------------
            # Fit
            # ------------------------------------------------

            fit_start = (
                time.perf_counter()
            )

            model.fit(
                X_train,
                y_train,
            )

            from src.models.inference import save_ml
            save_ml(
                model, model_name, kpi, feature_columns,
                output_dir=model_output_dir,
            )

            fit_seconds = (
                time.perf_counter()
                - fit_start
            )

            # ------------------------------------------------
            # Predict
            # ------------------------------------------------

            predict_start = (
                time.perf_counter()
            )

            y_pred = model.predict(
                X_test
            )

            predict_seconds = (
                time.perf_counter()
                - predict_start
            )

            y_pred = np.asarray(
                y_pred,
                dtype=np.float32,
            )

            # ------------------------------------------------
            # Metrics
            # ------------------------------------------------

            (
                mae,
                rmse,
                r2,
            ) = calculate_metrics(
                y_test,
                y_pred,
            )

            metrics_records.append({
                "target": kpi,
                "model": model_name,
                "MAE": mae,
                "RMSE": rmse,
                "R2": r2,
                "fit_seconds": (
                    float(
                        fit_seconds
                    )
                ),
                "predict_seconds": (
                    float(
                        predict_seconds
                    )
                ),
                "train_rows": len(
                    train_indices
                ),
                "test_rows": len(
                    test_indices
                ),
                "feature_count": len(
                    feature_columns
                ),
            })

            print(
                f"  MAE:  "
                f"{mae:.6f}"
            )

            print(
                f"  RMSE: "
                f"{rmse:.6f}"
            )

            print(
                f"  R²:   "
                f"{r2:.6f}"
            )

            print(
                f"  Fit:  "
                f"{fit_seconds:.1f} s"
            )

            print(
                f"  Pred: "
                f"{predict_seconds:.1f} s"
            )

            # ------------------------------------------------
            # Mean prediction by time
            # ------------------------------------------------

            (
                _,
                prediction_mean,
            ) = aggregate_by_time(
                target_times_test,
                y_pred,
            )

            for (
                target_time,
                actual_value,
                prediction_value,
            ) in zip(
                unique_test_times,
                actual_mean,
                prediction_mean,
            ):

                prediction_records.append({
                    "target": kpi,
                    "model": model_name,
                    "target_time": int(
                        target_time
                    ),
                    "actual_mean": float(
                        actual_value
                    ),
                    "prediction_mean": float(
                        prediction_value
                    ),
                })

            # ------------------------------------------------
            # Free model memory before next model
            # ------------------------------------------------

            del model
            del y_pred

            gc.collect()

        del y_train
        del y_test

        gc.collect()

    # --------------------------------------------------------
    # Convert results
    # --------------------------------------------------------

    metrics_df = pd.DataFrame(
        metrics_records
    )

    prediction_df = pd.DataFrame(
        prediction_records
    )

    return (
        metrics_df,
        prediction_df,
    )


# ============================================================
# Save run configuration
# ============================================================

def save_run_config(
    quick,
    feature_columns,
    metrics_df,
    output_file=None,
):
    """
    Save experiment metadata for reproducibility.
    """

    output_file = Path(output_file) if output_file is not None else RUN_CONFIG_FILE
    output_file.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    config = {
        "experiment": {
            "task": (
                "1-hour-ahead "
                "beam-level KPI regression"
            ),
            "targets": KPI_COLUMNS,
            "quick_mode": bool(
                quick
            ),
        },

        "features": {
            "count": len(
                feature_columns
            ),
            "columns": (
                feature_columns
            ),
        },

        "models": [
            "Persistence",
            "LinearRegression",
            "DecisionTree",
            "RandomForest",
            "XGBoost",
            "LightGBM",
        ],

        "metrics": [
            "MAE",
            "RMSE",
            "R2",
        ],

        "result_rows": int(
            len(metrics_df)
        ),

        "random_state": (
            RANDOM_STATE
        ),
    }

    with open(
        output_file,
        "w",
        encoding="utf-8",
    ) as file:

        json.dump(
            config,
            file,
            indent=2,
            ensure_ascii=False,
        )


# ============================================================
# Main
# ============================================================

def main(quick=False, output_dir=None, max_train=200000, max_test=0):
    """Run traditional ML with optional isolated outputs for Web experiments."""
    if max_train < 1 or max_test < 0:
        raise ValueError("Invalid quick-mode sample limits")
    if not quick and (max_train != 200000 or max_test != 0):
        raise ValueError("Sample limits require --quick")

    output_root = Path(output_dir) if output_dir is not None else None
    report_dir = output_root / "reports" if output_root else REPORT_DIR
    figure_dir = output_root / "figures" if output_root else FIGURE_DIR
    model_dir = output_root / "models" if output_root else None
    metrics_file = report_dir / METRICS_FILE.name
    prediction_file = report_dir / PREDICTION_SUMMARY_FILE.name
    config_file = report_dir / RUN_CONFIG_FILE.name

    # --------------------------------------------------------
    # Load feature definition
    # --------------------------------------------------------

    (
        feature_summary,
        feature_columns,
        target_columns,
        current_raw_columns,
    ) = load_feature_summary()

    # --------------------------------------------------------
    # Load feature dataset
    # --------------------------------------------------------

    df = load_ml_data()

    # --------------------------------------------------------
    # Validate required columns
    # --------------------------------------------------------

    required_columns = (
        [
            "target_time",
            "is_train",
        ]
        + feature_columns
        + target_columns
        + current_raw_columns
    )

    missing_columns = [
        column
        for column in required_columns
        if column not in df.columns
    ]

    if missing_columns:
        raise ValueError(
            "Missing required ML columns: "
            f"{missing_columns}"
        )

    # --------------------------------------------------------
    # Train and evaluate
    # --------------------------------------------------------

    (
        metrics_df,
        prediction_df,
    ) = run_experiment(
        df,
        feature_columns,
        current_raw_columns,
        quick=quick,
        max_train=max_train,
        max_test=max_test,
        model_output_dir=model_dir,
    )

    # Large source dataframe no longer needed.
    del df

    gc.collect()

    # --------------------------------------------------------
    # Save reports
    # --------------------------------------------------------

    report_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    metrics_df.to_csv(
        metrics_file,
        index=False,
        float_format="%.8g",
    )

    prediction_df.to_csv(
        prediction_file,
        index=False,
        float_format="%.8g",
    )

    save_run_config(
        quick,
        feature_columns,
        metrics_df,
        output_file=config_file,
    )

    print(
        f"\nMetrics saved: "
        f"{metrics_file}"
    )

    print(
        f"Prediction summary saved: "
        f"{prediction_file}"
    )

    # --------------------------------------------------------
    # Prediction figures
    # --------------------------------------------------------

    for kpi in KPI_COLUMNS:

        plot_prediction_curve(
            kpi,
            prediction_df,
            figure_dir=figure_dir,
        )

    # --------------------------------------------------------
    # Metric comparison figures
    # --------------------------------------------------------

    for metric in [
        "MAE",
        "RMSE",
        "R2",
    ]:

        plot_metric_comparison(
            metrics_df,
            metric,
            figure_dir=figure_dir,
        )

    # --------------------------------------------------------
    # Console summary
    # --------------------------------------------------------

    print(
        "\n" + "=" * 70
    )

    print(
        "W4 traditional ML experiment completed."
    )

    print(
        "=" * 70
    )

    print(
        "\nBest model by R² for each KPI:"
    )

    best_rows = (
        metrics_df
        .sort_values(
            by="R2",
            ascending=False,
        )
        .groupby(
            "target",
            as_index=False,
        )
        .first()
    )

