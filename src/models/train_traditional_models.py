def load_feature_summary():
    """
    Load feature names and target definitions generated by
    build_ml_features.py.
    """

    if not FEATURE_SUMMARY_FILE.exists():
        raise FileNotFoundError(
            f"Feature summary not found: "
            f"{FEATURE_SUMMARY_FILE}"
        )

    with open(
        FEATURE_SUMMARY_FILE,
        "r",
        encoding="utf-8",
    ) as file:
        summary = json.load(file)

    feature_columns = (
        summary[
            "features"
        ][
            "feature_columns"
        ]
    )

    target_columns = (
        summary[
            "forecast"
        ][
            "target_columns"
        ]
    )

    current_raw_columns = (
        summary[
            "features"
        ][
            "current_raw_columns_for_persistence"
        ]
    )

    return (
        summary,
        feature_columns,
        target_columns,
        current_raw_columns,
    )


