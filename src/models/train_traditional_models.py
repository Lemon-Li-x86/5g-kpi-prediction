def build_models(quick=False):
    """
    Build the five required regression models.

    quick=True:
        smaller models for debugging only

    quick=False:
        normal W4 experiment
    """

    if XGBRegressor is None:
        raise ImportError(
            "xgboost is not installed.\n"
            "Run: pip install xgboost"
        )

    if LGBMRegressor is None:
        raise ImportError(
            "lightgbm is not installed.\n"
            "Run: pip install lightgbm"
        )

    if quick:
        rf_estimators = 10
        xgb_estimators = 50
        lgb_estimators = 50

    else:
        rf_estimators = 30
        xgb_estimators = 250
        lgb_estimators = 250

    models = {
        "LinearRegression": (
            LinearRegression(
                n_jobs=-1
            )
        ),

        "DecisionTree": (
            DecisionTreeRegressor(
                max_depth=18,
                min_samples_leaf=20,
                random_state=RANDOM_STATE,
            )
        ),

        "RandomForest": (
            RandomForestRegressor(
                n_estimators=rf_estimators,
                max_depth=16,
                min_samples_leaf=20,
                max_features="sqrt",
                max_samples=0.6,
                n_jobs=-1,
                random_state=RANDOM_STATE,
                verbose=0,
            )
        ),

        "XGBoost": (
            XGBRegressor(
                n_estimators=xgb_estimators,
                max_depth=8,
                learning_rate=0.05,
                subsample=0.8,
                colsample_bytree=0.8,
                objective="reg:squarederror",
                tree_method="hist",
                n_jobs=-1,
                random_state=RANDOM_STATE,
                verbosity=0,
            )
        ),

        "LightGBM": (
            LGBMRegressor(
                n_estimators=lgb_estimators,
                num_leaves=63,
                max_depth=-1,
                learning_rate=0.05,
                subsample=0.8,
                colsample_bytree=0.8,
                min_child_samples=20,
                n_jobs=-1,
                random_state=RANDOM_STATE,
                verbose=-1,
            )
        ),
    }

    return models


# ============================================================
# Evaluation
# ============================================================

def calculate_metrics(
    y_true,
    y_pred,
):
    """
    Calculate regression metrics.

    Returns:
        MAE
        RMSE
        R²
    """

    mae = mean_absolute_error(
        y_true,
        y_pred,
    )

    rmse = np.sqrt(
        mean_squared_error(
            y_true,
            y_pred,
        )
    )

    r2 = r2_score(
        y_true,
        y_pred,
    )

    return (
        float(mae),
        float(rmse),
        float(r2),
    )


# ============================================================
# Time aggregation
# ============================================================

def aggregate_by_time(
    target_times,
    values,
):
    """
    Aggregate beam-level predictions into mean KPI value
    for each target time.

    This produces readable prediction curves with 168 test
    timestamps instead of plotting 483,840 individual rows.
    """

    target_times = np.asarray(
        target_times,
        dtype=np.int32,
    )

    values = np.asarray(
        values,
        dtype=np.float64,
    )

    min_time = int(
        target_times.min()
    )

    max_time = int(
        target_times.max()
    )

    indices = (
        target_times
        - min_time
    )

    n_times = (
        max_time
        - min_time
        + 1
    )

    sums = np.bincount(
        indices,
        weights=values,
        minlength=n_times,
    )

    counts = np.bincount(
        indices,
        minlength=n_times,
    )

    means = (
        sums
        / counts
    )

    times = np.arange(
        min_time,
        max_time + 1,
        dtype=np.int32,
    )

    return (
        times,
        means,
    )


# ============================================================
# Plot prediction curves
# ============================================================

def plot_prediction_curve(
    target_name,
    prediction_df,
    figure_dir=None,
):
    """
    Plot mean observed and predicted KPI values over test time.
    """

    figure_dir = Path(figure_dir) if figure_dir is not None else FIGURE_DIR
    figure_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    target_data = (
        prediction_df[
            prediction_df[
                "target"
            ] == target_name
        ]
        .copy()
    )

    if target_data.empty:
        return

    pivot = target_data.pivot(
        index="target_time",
        columns="model",
        values="prediction_mean",
    )

    actual = (
        target_data[
            [
                "target_time",
                "actual_mean",
            ]
        ]
        .drop_duplicates()
        .sort_values(
            "target_time"
        )
        .set_index(
            "target_time"
        )
    )

    plt.figure(
        figsize=(12, 6)
    )

    plt.plot(
        actual.index,
        actual[
            "actual_mean"
        ],
        linewidth=2.2,
        label="Actual",
    )

    for model_name in pivot.columns:

        plt.plot(
            pivot.index,
            pivot[
                model_name
            ],
            linewidth=1.2,
            alpha=0.8,
            label=model_name,
        )

    plt.title(
        f"{target_name}: "
        f"1-hour-ahead prediction"
    )

    plt.xlabel(
        "Target time"
    )

    plt.ylabel(
        target_name
    )

    plt.grid(
        alpha=0.25
    )

    plt.legend(
        fontsize=8,
        ncol=2,
    )

    plt.tight_layout()

    output_path = (
        figure_dir
        / f"{target_name}_predictions.png"
    )

    plt.savefig(
        output_path,
        dpi=160,
        bbox_inches="tight",
    )

    plt.close()

    print(
        f"Saved figure: "
        f"{output_path}"
    )


